def load_segments(blob: bytes) -> list[tuple[int, int, int]]:
    if blob[:5] != b"\x7fELF\x02" or blob[5] != 1:
        raise ValueError("artifact is not a little-endian ELF64 file")
    e_phoff = struct.unpack_from("<Q", blob, 32)[0]
    e_phentsize = struct.unpack_from("<H", blob, 54)[0]
    e_phnum = struct.unpack_from("<H", blob, 56)[0]
    segments: list[tuple[int, int, int]] = []
    for index in range(e_phnum):
        off = e_phoff + index * e_phentsize
        p_type, _, p_offset, p_vaddr, _, p_filesz, _, _ = struct.unpack_from(
            "<IIQQQQQQ", blob, off
        )
        if p_type == 1 and p_filesz:
            segments.append((p_offset, p_vaddr, p_filesz))
    if not segments:
        raise ValueError("ELF has no file-backed PT_LOAD segments")
    return segments


def va_to_file(segments: list[tuple[int, int, int]], va: int, size: int = 1) -> int:
    for p_offset, p_vaddr, p_filesz in segments:
        if p_vaddr <= va and va + size <= p_vaddr + p_filesz:
            return p_offset + va - p_vaddr
    raise ValueError(f"VA {va:#x}+{size:#x} is not file-backed")


def read_u16(blob: bytes, segments: list[tuple[int, int, int]], va: int) -> int:
    return struct.unpack_from("<H", blob, va_to_file(segments, va, 2))[0]


def read_u32(blob: bytes, segments: list[tuple[int, int, int]], va: int) -> int:
    return struct.unpack_from("<I", blob, va_to_file(segments, va, 4))[0]


def read_u64(blob: bytes, segments: list[tuple[int, int, int]], va: int) -> int:
    return struct.unpack_from("<Q", blob, va_to_file(segments, va, 8))[0]


def aarch64_direct_bl_target(va: int, word: int) -> int | None:
    if word & 0xFC00_0000 != 0x9400_0000:
        return None
    immediate = word & 0x03FF_FFFF
    if immediate & 0x0200_0000:
        immediate -= 0x0400_0000
    return va + immediate * 4


def s19k_reg0c_plan(address_gap: int = 2, asic_count: int = 77) -> list[tuple[int, int, int]]:
    """Return (chip index, wire address, semantic register value)."""
    value_step = 0xFFFF // asic_count
    return [
        (index, address_gap * index, 0x8000_0000 | value_step * index)
        for index in range(asic_count)
    ]


def s19k_set_address_plan(
    address_gap: int = 2, asic_count: int = 77
) -> list[tuple[int, int]]:
    """Return the direct-generic (chip index, wire address) ladder."""
    if address_gap <= 0 or asic_count <= 0:
        raise ValueError("SetAddress geometry must be nonzero")
    if address_gap * (asic_count - 1) > 0xFF:
        raise ValueError("SetAddress destination exceeds one byte")
    return [(index, address_gap * index) for index in range(asic_count)]


def generic_core3c_value(fields: tuple[int, ...]) -> int:
    """Reproduce the caller-derived register-0x3c assembly at 0x838750."""
    if len(fields) != 8 or any(not 0 <= value <= 0xFF for value in fields):
        raise ValueError("generic Core3c input must be eight bytes")
    low = fields[5] & 0x7F
    if fields[0] == 0:
        low |= 0x80
    high_middle = fields[4]
    if fields[1] == 0:
        high_middle |= 0x80
    if fields[2] == 0:
        high_middle |= 0x40
    if fields[3] == 0:
        high_middle |= 0x20
    return fields[7] << 24 | high_middle << 16 | fields[6] << 8 | low


def io_driver_value(high_nibble: int) -> int:
    if not 0 <= high_nibble <= 0xF:
        raise ValueError("IoDriver caller field escaped four bits")
    return 0x0211_0111 | high_nibble << 12


def s19k_finalize_plan(
    address_gap: int = 2,
    asic_count: int = 77,
    asics_per_domain: int = 7,
) -> tuple[list[tuple[int, int, int, int]], list[tuple[int, int, int, int, int, int, int]]]:
    """Return endpoint-IoDriver and paired-UART-relay schedules.

    The caller-provided IoDriver nibble is shown with the S19k cross-corpus
    value F.  Tuple members are intentionally numeric rather than guessed
    stripped source identifiers.
    """
    if asic_count % asics_per_domain:
        raise ValueError("S19k finalize example requires divisible domains")
    domains = asic_count // asics_per_domain
    io_steps: list[tuple[int, int, int, int]] = []
    relay_steps: list[tuple[int, int, int, int, int, int, int]] = []
    for from_end in range(1, domains + 1):
        domain = domains - from_end
        first = asic_count - from_end * asics_per_domain
        second = asic_count - (from_end - 1) * asics_per_domain - 1
        gap_count = from_end * asics_per_domain + 14
        io_steps.append((domain, second, address_gap * second, io_driver_value(0xF)))
        relay_steps.append(
            (
                domain,
                first,
                address_gap * first,
                second,
                address_gap * second,
                gap_count,
                gap_count << 16 | 3,
            )
        )
    return io_steps, relay_steps


